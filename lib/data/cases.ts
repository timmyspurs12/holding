const MODELS = [
  "Claude Opus 4",
  "GPT-5",
  "Gemini 2.5 Pro",
  "Llama 4 Maverick",
  "Mistral Large 3",
];

function panel(votes: ("FOLLOW" | "DISTINGUISH")[], notes: string[]): PanelMember[] {
  return votes.map((vote, i) => ({
    index: i + 1,
    model: MODELS[i % MODELS.length],
    vote,
    reviewed: true,
    note: notes[i] ?? "Consistent with the retrieved line of authority.",
  }));
}

